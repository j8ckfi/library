"""L3 derived index: graph/INDEX.md and the AGENTS.md cheat-sheet view."""

import re
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from library.graph import KnowledgeGraph, Node

CHEAT_START = "<!-- CHEAT-SHEET:START -->"
CHEAT_END = "<!-- CHEAT-SHEET:END -->"
INDEX_BANNER = "<!-- GENERATED BY python -m library index. DO NOT HAND-EDIT. -->"


def infer_graph_root(graph: KnowledgeGraph) -> Optional[Path]:
    for node in graph.nodes.values():
        if not node.file_path:
            continue
        path = Path(node.file_path).resolve()
        if path.parent.name in ("tasks", "methods", "papers", "recipes"):
            return path.parent.parent
    return None


def repo_paths(graph: KnowledgeGraph, graph_root: Optional[Path] = None) -> Dict[str, Path]:
    root = Path(graph_root).resolve() if graph_root is not None else infer_graph_root(graph)
    if root is None:
        root = Path("graph").resolve()
    repo_root = root.parent if root.name == "graph" else root
    return {
        "graph_root": root,
        "repo_root": repo_root,
        "index_path": root / "INDEX.md",
        "agents_path": repo_root / "AGENTS.md",
        "changelog_path": root / "CHANGELOG.md",
    }


def _arxiv_for_method(graph: KnowledgeGraph, method: Optional[Node]) -> str:
    if method is None:
        return ""
    for paper_id in method.metadata.get("papers") or []:
        paper = graph.get_node(paper_id)
        if paper and paper.metadata.get("arxiv_id"):
            return str(paper.metadata.get("arxiv_id"))
    return ""


def _method_label(graph: KnowledgeGraph, method_id: str) -> str:
    method = graph.get_node(method_id)
    slug = method_id.split(":", 1)[-1] if method_id else method_id
    arxiv = _arxiv_for_method(graph, method)
    if arxiv:
        return f"{method_id} ({arxiv})"
    return method_id if method_id else slug


def _sota_entries(task: Node) -> List[dict]:
    entries = []
    for item in task.metadata.get("current_sota") or []:
        if isinstance(item, dict) and item.get("method"):
            entries.append(item)
    return entries


def _redirects(node: Node) -> List[dict]:
    rows = []
    for item in node.metadata.get("redirects") or []:
        if isinstance(item, dict) and item.get("when") and item.get("to"):
            rows.append({"when": str(item["when"]), "to": str(item["to"])})
    return rows


def _do_not_use(node: Node) -> List[dict]:
    rows = []
    for item in node.metadata.get("do_not_use_for") or []:
        if isinstance(item, dict) and item.get("when"):
            rows.append({
                "when": str(item.get("when")),
                "reason": str(item.get("reason") or ""),
                "use_instead": str(item.get("use_instead") or ""),
            })
    return rows


def iter_index_rows(graph: KnowledgeGraph) -> List[dict]:
    rows = []
    tasks = sorted(
        graph.get_nodes_by_type("task"),
        key=lambda n: ((n.domain or ""), n.id),
    )
    for task in tasks:
        sota = _sota_entries(task)
        methods = []
        for entry in sota:
            method = graph.get_node(entry["method"])
            methods.append({
                "id": entry["method"],
                "as_of": str(entry.get("as_of") or ""),
                "value": entry.get("value"),
                "benchmark": entry.get("benchmark"),
                "notes": entry.get("notes") or "",
                "arxiv": _arxiv_for_method(graph, method),
                "do_not_use_for": _do_not_use(method) if method else [],
            })
        rows.append({
            "id": task.id,
            "title": task.title,
            "domain": task.domain or "",
            "summary": task.metadata.get("summary") or "",
            "scope": task.metadata.get("scope") or "",
            "out_of_scope": list(task.metadata.get("out_of_scope") or []),
            "redirects": _redirects(task),
            "sota": methods,
            "last_reviewed": str(task.metadata.get("last_reviewed") or ""),
        })
    return rows


def render_cheat_sheet(graph: KnowledgeGraph) -> str:
    """Compact first-hop table: one primary line per task, indented redirects."""
    lines: List[str] = []
    for row in iter_index_rows(graph):
        if row["sota"]:
            bits = []
            for method in row["sota"]:
                label = method["id"]
                extra = []
                if method["arxiv"]:
                    extra.append(method["arxiv"])
                if method["as_of"]:
                    extra.append(method["as_of"])
                if extra:
                    label = f"{label} ({', '.join(extra)})"
                bits.append(label)
            sota_bit = " + ".join(bits)
        else:
            sota_bit = "(no current_sota)"
        lines.append(f"{row['id']} -> {sota_bit}")
        for redirect in row["redirects"]:
            lines.append(f"  when {redirect['when']} -> {redirect['to']}")
    return "\n".join(lines)


def render_index_markdown(graph: KnowledgeGraph) -> str:
    rows = iter_index_rows(graph)
    parts = [
        INDEX_BANNER,
        "",
        "# SOTA Index",
        "",
        "Derived from task `current_sota`, task `redirects`, and method `do_not_use_for`.",
        "Regenerate with `python -m library index`. Never hand-edit this file.",
        "",
    ]
    current_domain = None
    for row in rows:
        domain = row["domain"] or "unspecified"
        if domain != current_domain:
            current_domain = domain
            parts.append(f"## {domain}")
            parts.append("")
        parts.append(f"### {row['id']} — {row['title']}")
        if row["scope"]:
            parts.append(f"- **Scope**: {row['scope']}")
        if row["sota"]:
            for method in row["sota"]:
                claim = ""
                if method["benchmark"] is not None and method["value"] is not None:
                    claim = f" — {method['benchmark']}: {method['value']}"
                arxiv = f" `{method['arxiv']}`" if method["arxiv"] else ""
                as_of = f" (as_of {method['as_of']})" if method["as_of"] else ""
                parts.append(f"- **SOTA**: `{method['id']}`{arxiv}{as_of}{claim}")
                for guard in method["do_not_use_for"]:
                    instead = f" → `{guard['use_instead']}`" if guard["use_instead"] else ""
                    parts.append(f"  - do not use when {guard['when']}{instead}")
        else:
            parts.append("- **SOTA**: (none recorded)")
        if row["redirects"]:
            parts.append("- **Redirects**:")
            for redirect in row["redirects"]:
                parts.append(f"  - when {redirect['when']} → `{redirect['to']}`")
        if row["out_of_scope"]:
            parts.append("- **Out of scope**: " + "; ".join(row["out_of_scope"]))
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def wrap_cheat_sheet_block(inner: str) -> str:
    return f"{CHEAT_START}\n```\n{inner.rstrip()}\n```\n{CHEAT_END}"


def replace_cheat_sheet(agents_text: str, inner: str) -> str:
    block = wrap_cheat_sheet_block(inner)
    pattern = re.compile(re.escape(CHEAT_START) + r".*?" + re.escape(CHEAT_END), re.DOTALL)
    if pattern.search(agents_text):
        return pattern.sub(block, agents_text, count=1)
    section = re.search(r"(## 2\. Agent Routing Cheat-Sheet[^\n]*\n)", agents_text)
    if section:
        fence = re.search(r"```.*?```", agents_text[section.end():], re.DOTALL)
        if fence:
            start = section.end() + fence.start()
            end = section.end() + fence.end()
            return agents_text[:start] + block + agents_text[end:]
    return agents_text.rstrip() + "\n\n" + block + "\n"


def extract_cheat_sheet_inner(agents_text: str) -> Optional[str]:
    pattern = re.compile(
        re.escape(CHEAT_START) + r"\s*```[^\n]*\n(.*?)```\s*" + re.escape(CHEAT_END),
        re.DOTALL,
    )
    match = pattern.search(agents_text)
    if not match:
        return None
    return match.group(1).strip("\n")


def derived_drift(
    graph: KnowledgeGraph,
    index_path: Optional[Path] = None,
    agents_path: Optional[Path] = None,
) -> List[str]:
    """Return human-readable drift messages. Empty means views match graph state."""
    paths = repo_paths(graph)
    index_path = Path(index_path) if index_path is not None else paths["index_path"]
    agents_path = Path(agents_path) if agents_path is not None else paths["agents_path"]
    messages: List[str] = []
    expected_index = render_index_markdown(graph)
    if not index_path.exists():
        messages.append(f"{index_path} is missing; run `python -m library index`")
    else:
        actual = index_path.read_text(encoding="utf-8")
        if actual != expected_index:
            messages.append(f"{index_path} is stale vs graph state; run `python -m library index`")
    expected_cheat = render_cheat_sheet(graph)
    if not agents_path.exists():
        messages.append(f"{agents_path} is missing; cannot verify cheat-sheet view")
    else:
        agents_text = agents_path.read_text(encoding="utf-8")
        if CHEAT_START not in agents_text or CHEAT_END not in agents_text:
            messages.append(
                f"{agents_path} cheat-sheet markers missing; run `python -m library index`"
            )
        else:
            inner = extract_cheat_sheet_inner(agents_text)
            if inner != expected_cheat:
                messages.append(
                    f"{agents_path} cheat-sheet is stale vs graph state; run `python -m library index`"
                )
    return messages


def write_index(
    graph: KnowledgeGraph,
    graph_root: Optional[Path] = None,
    agents_path: Optional[Path] = None,
) -> Dict[str, object]:
    """Write INDEX.md and refresh the AGENTS.md cheat-sheet. Returns {written, stale}."""
    paths = repo_paths(graph, graph_root)
    index_path = paths["index_path"]
    agents = Path(agents_path) if agents_path is not None else paths["agents_path"]
    stale_before = bool(derived_drift(graph, index_path=index_path, agents_path=agents))

    expected_index = render_index_markdown(graph)
    expected_cheat = render_cheat_sheet(graph)
    written: List[str] = []

    index_path.parent.mkdir(parents=True, exist_ok=True)
    index_path.write_text(expected_index, encoding="utf-8")
    written.append(str(index_path))

    if agents.exists():
        updated = replace_cheat_sheet(agents.read_text(encoding="utf-8"), expected_cheat)
        agents.write_text(updated, encoding="utf-8")
        written.append(str(agents))
    else:
        agents.write_text(
            "# AGENTS.md\n\n## 2. Agent Routing Cheat-Sheet (First-Hop SOTA Index)\n\n"
            + wrap_cheat_sheet_block(expected_cheat)
            + "\n",
            encoding="utf-8",
        )
        written.append(str(agents))

    return {"written": written, "stale": stale_before}
